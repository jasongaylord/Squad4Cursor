import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export type AgentDef = {
  name: string;
  role: string;
  model?: string;
  charter?: string;
};

export type TeamDef = {
  name: string;
  members: string[];
};

export type SquadDef = {
  team: TeamDef;
  agents: AgentDef[];
  modelProfile?: "quality" | "balanced" | "economy";
  routingExtra?: string;
};

export function defineAgent(agent: AgentDef): AgentDef {
  return agent;
}

export function defineTeam(team: TeamDef): TeamDef {
  return team;
}

export function defineSquad(squad: SquadDef): SquadDef {
  return squad;
}

function ensureDir(path: string): void {
  mkdirSync(path, { recursive: true });
}

function write(path: string, contents: string): void {
  ensureDir(dirname(path));
  writeFileSync(path, contents, "utf8");
}

function defaultCharter(agent: AgentDef): string {
  return (
    agent.charter ??
    `# ${agent.role}

## Role

${agent.role} (id: \`${agent.name}\`).

## Responsibilities

- Own work matching this role
- Update history.md with durable learnings

## Isolation

Load only this charter, this history, and relevant decisions.md slices.
`
  );
}

function defaultHistory(role: string): string {
  return `# ${role} History

## Project knowledge

(none yet)

## Recent sessions

(none yet)
`;
}

export type GenerateResult = { messages: string[] };

/** Generate Brady-compatible .squad/ files from a typed SquadDef. */
export async function generateSquadFiles(
  projectRoot: string,
  config: unknown,
): Promise<GenerateResult> {
  const squad = config as SquadDef;
  if (!squad?.team || !Array.isArray(squad.agents)) {
    throw new Error("Invalid squad config: expected { team, agents }");
  }

  const messages: string[] = [];
  const root = join(projectRoot, ".squad");
  ensureDir(root);

  const rows = [
    ...squad.agents.map((a) => `| ${a.role} | ${a.name} | active |`),
    `| Scribe | scribe | active |`,
  ];

  write(
    join(root, "team.md"),
    `# Team Roster

**${squad.team.name}**

| Role | Agent | Status |
| --- | --- | --- |
${rows.join("\n")}

## Notes

- Generated by @squad4cursor/sdk from squad.config.ts
`,
  );
  messages.push("Wrote team.md");

  const routingRows = squad.agents
    .map((a) => `| ${a.role} work | ${a.role} | Lead | Tester, Lead |`)
    .join("\n");

  write(
    join(root, "routing.md"),
    `# Routing

| Intent | Primary | Supporting | Review |
| --- | --- | --- | --- |
| Architecture | Lead | — | Lead |
${routingRows}
| Memory | Scribe | — | — |

${squad.routingExtra ?? ""}

## Rules

1. Parallelize independent work.
2. Reviewer lockout on REJECT.
3. Scribe never implements product code.
`,
  );
  messages.push("Wrote routing.md");

  write(
    join(root, "decisions.md"),
    `# Decisions

## Log

<!-- Decisions are appended below -->
`,
  );

  write(
    join(root, "config.json"),
    JSON.stringify(
      {
        version: "0.2.0",
        runtime: "squad4cursor",
        modelProfile: squad.modelProfile ?? "quality",
        createdBy: "squad4cursor-sdk",
        models: Object.fromEntries(
          squad.agents.filter((a) => a.model).map((a) => [a.name, a.model]),
        ),
        compat: { bradySquad: true, cursor: true, copilot: true },
      },
      null,
      2,
    ) + "\n",
  );
  messages.push("Wrote config.json");

  write(join(root, "identity", "now.md"), `# Now\n\n**Focus**: (unset)\n`);
  write(join(root, "identity", "wisdom.md"), `# Wisdom\n\n`);
  write(
    join(root, "casting", "policy.json"),
    JSON.stringify({ theme: "default", persistNames: true, allowUserOverrides: true }, null, 2) +
      "\n",
  );
  write(join(root, "casting", "registry.json"), JSON.stringify({ names: {} }, null, 2) + "\n");
  write(
    join(root, "casting", "history.json"),
    JSON.stringify({ universes: [], assignments: [] }, null, 2) + "\n",
  );

  // Scribe
  write(
    join(root, "agents", "scribe", "charter.md"),
    `# Scribe\n\nSilent memory manager.\n`,
  );
  write(join(root, "agents", "scribe", "history.md"), defaultHistory("Scribe"));

  for (const agent of squad.agents) {
    write(join(root, "agents", agent.name, "charter.md"), defaultCharter(agent));
    write(join(root, "agents", agent.name, "history.md"), defaultHistory(agent.role));
    messages.push(`Wrote agents/${agent.name}/`);
  }

  write(
    join(root, "squad4cursor.json"),
    JSON.stringify({ version: "0.2.0", generatedBy: "sdk", at: new Date().toISOString() }, null, 2) +
      "\n",
  );

  messages.push(`Generated .squad/ for team "${squad.team.name}"`);
  return { messages };
}
